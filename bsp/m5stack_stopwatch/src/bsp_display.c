/* RGB565 lines whose width is odd may be padded by LVGL. CO5300 expects a
 * tightly packed color stream, therefore flush an even number of pixels. */
static void bsp_display_rounder_cb(lv_area_t *area)
{
    area->x1 &= ~1;
    area->x2 |= 1;
    if (area->x2 >= BSP_LCD_H_RES) {
        area->x2 = BSP_LCD_H_RES - 1;
    }
}
