static const char *TAG = "M5Stack StopWatch";

/* Same sequence as M5StopWatch-UserDemo Panel_CO5300::getInitCommands(). */
static const co5300_lcd_init_cmd_t lcd_init_cmds[] = {
    {0x11, NULL, 0, 150},                 /* Sleep out */
    {0xC4, (uint8_t []){0x80}, 1, 0},
    {0x35, (uint8_t []){0x80}, 1, 0},     /* Tearing effect on */
    {0x44, (uint8_t []){0x01, 0xD2}, 2, 0}, /* Tear scanline 0x1D2 = 466 */
    {0x53, (uint8_t []){0x20}, 1, 0},     /* Brightness control on */
    {0x20, NULL, 0, 0},                   /* Display inversion off */
    {0x36, (uint8_t []){0x00}, 1, 0},     /* MADCTL */
    {0x51, (uint8_t []){0xA0}, 1, 0},     /* Brightness */
    {0x29, NULL, 0, 0},                   /* Display on */
};


